"""C generator of the whole-program SPU tests: `python -m tests.spu_programs.gen --out DIR` (cwd tools/).

Every program is assembled, wrapped into a synthetic image (a code segment, and a data segment for the
jump table), recovered with `spu_recover.recover_image` and emitted with `spu_emit.emit_one`, the
steps `spu-emit` takes for a registry image. The output directory gets the files of `spu-emit`
(`spu_<image>_NNN.c`, `spu_tables.c`, `spu_funcs.h`, `spu_sources.cmake`) plus `spu_programs_data.h`/`.c`
with the image bytes and the constants the C++ driver shares with the programs.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from collections.abc import Callable, Sequence
from dataclasses import dataclass
from pathlib import Path

from ps3recomp import spu_emit, spu_images, spu_recover
from ps3recomp.emit_output import write_if_changed
from ps3recomp.info import CliError
from tests import spu_asm

from . import (BUF_LS, CHUNK_BYTES, CODE_LS, COUNTER_ROUNDS, IMAGE_EA, IMAGE_STRIDE, TABLE_ENTRIES, TABLE_LS)

HEADER_NAME = "spu_programs_data.h"
SOURCE_NAME = "spu_programs_data.c"
BANNER = "// Generated by tests.spu_programs.gen; do not edit."

# SPU channel numbers (SPU ISA 1.2, Channel Instructions; the runtime's spu_channels.h lists the same).
MFC_LSA, MFC_EAH, MFC_EAL, MFC_SIZE, MFC_TAG_ID, MFC_CMD = 16, 17, 18, 19, 20, 21
WR_TAG_MASK, WR_TAG_UPDATE, RD_TAG_STAT, RD_ATOMIC_STAT = 22, 23, 24, 27
WR_OUT_MBOX, RD_IN_MBOX, WR_OUT_INTR_MBOX = 28, 29, 30
MFC_GET, MFC_PUTLLC, MFC_GETLLAR = 0x40, 0xB4, 0xD0

# Results of the jump-table cases and of the default case (small enough for a signed 16-bit `il`).
TABLE_RESULTS = (0x1111, 0x2222, 0x3333, 0x4444)
TABLE_DEFAULT = 0x7777
# The event program writes this OutMbox value first (data3 of the event) and the interrupt word below.
EVENT_DATA3 = 0x77
EVENT_PORT = 16
EVENT_VALUE = 0x1234


class ProgramError(Exception):
    """A program cannot be turned into an image; the message is one line."""


class Assembler:
    """Labels and PC-relative branches on top of `spu_asm.encode`."""

    def __init__(self, base: int) -> None:
        self.base = base
        self._items: list[tuple[str, dict, str | None]] = []
        self._labels: dict[str, int] = {}

    def label(self, name: str) -> None:
        if name in self._labels:
            raise ProgramError("duplicate label %s" % name)
        self._labels[name] = self.base + 4 * len(self._items)

    def op(self, mnemonic: str, **fields: int) -> None:
        self._items.append((mnemonic, fields, None))

    def branch(self, mnemonic: str, target: str, **fields: int) -> None:
        self._items.append((mnemonic, fields, target))

    def addr(self, name: str) -> int:
        return self._labels[name]

    def words(self) -> tuple[int, ...]:
        out = []
        for index, (mnemonic, fields, target) in enumerate(self._items):
            addr = self.base + 4 * index
            if target is None:
                out.append(spu_asm.encode(mnemonic, **fields))
            elif target in self._labels:
                out.append(spu_asm.encode(mnemonic, addr=addr, target=self._labels[target], **fields))
            else:
                raise ProgramError("undefined label %s" % target)
        return tuple(out)

    # Shorthands for the instructions the programs use most.
    def wrch(self, channel: int, reg: int) -> None:
        self.op("wrch", CA=channel, RT=reg)

    def rdch(self, reg: int, channel: int) -> None:
        self.op("rdch", RT=reg, CA=channel)

    def stop(self, code: int) -> None:
        self.op("stop", STOP=code)


@dataclass(frozen=True)
class Program:
    name: str                                   # image name
    words: tuple[int, ...]
    data: tuple[tuple[int, bytes], ...] = ()    # (ls, bytes) of the non-code segments
    jump_tables: int = 0                        # jump tables the recovery has to find


# --- programs ---------------------------------------------------------------------------------


def sum_array() -> Program:
    """GETs the array of $3 (byte count in $4) in chunks and sums its big-endian words.

    The GET and the per-chunk sum are leaf functions reached with `brsl $0` and left with `bi $0`. The
    sum goes out through OutMbox, which `stop 0x102` takes as the thread status.
    """
    a = Assembler(CODE_LS)
    # Arguments are 64-bit values in the preferred doubleword, so the low word is word 1.
    a.op("rotqbyi", RT=10, RA=3, I7=4)      # r10 = array address
    a.op("rotqbyi", RT=11, RA=4, I7=4)      # r11 = bytes left
    a.op("il", RT=14, I16=CHUNK_BYTES)
    a.op("il", RT=20, I16=0)                # r20 = running sum, one partial sum per word lane
    a.label("next_chunk")
    a.branch("brsl", "get_chunk", RT=0)
    a.branch("brsl", "sum_chunk", RT=0)
    a.op("a", RT=10, RA=10, RB=14)
    a.op("sf", RT=11, RA=14, RB=11)         # sf computes RB - RA
    a.branch("brnz", "next_chunk", RT=11)
    # Horizontal add: lane 0 ends up with the sum of the four lanes.
    a.op("rotqbyi", RT=21, RA=20, I7=4)
    a.op("a", RT=20, RA=20, RB=21)
    a.op("rotqbyi", RT=21, RA=20, I7=8)
    a.op("a", RT=20, RA=20, RB=21)
    a.wrch(WR_OUT_MBOX, 20)
    a.stop(0x102)

    # get_chunk: GET CHUNK_BYTES from the address in r10 into the buffer and wait for the tag.
    a.label("get_chunk")
    a.op("ila", RT=30, I18=BUF_LS)
    a.op("il", RT=31, I16=0)
    a.op("il", RT=32, I16=CHUNK_BYTES)
    a.op("il", RT=33, I16=1)
    a.op("il", RT=34, I16=MFC_GET)
    a.op("il", RT=35, I16=2)                # tag mask for tag 1, and update mode 2 (wait for all)
    a.wrch(MFC_LSA, 30)
    a.wrch(MFC_EAH, 31)
    a.wrch(MFC_EAL, 10)
    a.wrch(MFC_SIZE, 32)
    a.wrch(MFC_TAG_ID, 33)
    a.wrch(MFC_CMD, 34)
    a.wrch(WR_TAG_MASK, 35)
    a.wrch(WR_TAG_UPDATE, 35)
    a.rdch(36, RD_TAG_STAT)
    a.op("bi", RA=0)

    # sum_chunk: add the quadwords of the buffer to r20.
    a.label("sum_chunk")
    a.op("ila", RT=40, I18=BUF_LS)
    a.op("il", RT=41, I16=CHUNK_BYTES // 16)
    a.label("sum_loop")
    a.op("lqd", RT=42, I10x16=0, RA=40)
    a.op("a", RT=20, RA=20, RB=42)
    a.op("ai", RT=40, RA=40, I10=16)
    a.op("ai", RT=41, RA=41, I10=-1)
    a.branch("brnz", "sum_loop", RT=41)
    a.op("bi", RA=0)
    return Program("sum_array", a.words())


def atomic_counter() -> Program:
    """Adds one to the word at the 16-byte aligned address in $3, COUNTER_ROUNDS times.

    Each add is a GETLLAR / PUTLLC pair that repeats until the conditional put succeeds. The other
    words of the reservation line are written back unchanged.
    """
    a = Assembler(CODE_LS)
    a.op("rotqbyi", RT=10, RA=3, I7=4)      # r10 = counter address
    a.op("andi", RT=11, RA=10, I10=0x7F)    # r11 = offset in the reservation line
    a.op("andi", RT=12, RA=10, I10=-128)    # r12 = line address
    a.op("ila", RT=13, I18=BUF_LS)          # r13 = LS copy of the line
    a.op("il", RT=16, I16=0)
    a.op("il", RT=17, I16=128)
    a.op("il", RT=28, I16=MFC_GETLLAR)
    a.op("il", RT=29, I16=MFC_PUTLLC)
    a.op("il", RT=15, I16=COUNTER_ROUNDS)
    a.op("il", RT=23, I16=-1)
    a.op("shlqbyi", RT=23, RA=23, I7=12)    # r23 = select mask of word 0
    a.label("again")
    # r28 and r29 hold the GETLLAR and PUTLLC commands; the GETLLAR status goes to r18, the PUTLLC one to r19.
    for cmd in (28, 29):
        if cmd == 29:
            # Modify the counter word in the copy of the line.
            a.op("lqx", RT=20, RA=13, RB=11)
            a.op("ai", RT=26, RA=20, I10=1)
            a.op("selb", RT4=27, RA=20, RB=26, RC=23)
            a.op("stqx", RT=27, RA=13, RB=11)
        a.wrch(MFC_LSA, 13)
        a.wrch(MFC_EAH, 16)
        a.wrch(MFC_EAL, 12)
        a.wrch(MFC_SIZE, 17)
        a.wrch(MFC_TAG_ID, 16)
        a.wrch(MFC_CMD, cmd)
        a.rdch(18 if cmd == 28 else 19, RD_ATOMIC_STAT)
    a.op("andi", RT=19, RA=19, I10=1)       # bit 0: the conditional put failed
    a.branch("brnz", "again", RT=19)
    a.op("ai", RT=15, RA=15, I10=-1)
    a.branch("brnz", "again", RT=15)
    a.wrch(WR_OUT_MBOX, 15)
    a.stop(0x102)
    return Program("atomic_counter", a.words())


def jump_table() -> Program:
    """Selects a result by the argument in $3 through a table of code addresses.

    Out-of-range selectors take the default case. The result is stored in the first word of BUF_LS
    and goes out through OutMbox.
    """
    a = Assembler(CODE_LS)
    a.op("rotqbyi", RT=10, RA=3, I7=4)      # r10 = selector
    a.op("clgti", RT=11, RA=10, I10=TABLE_ENTRIES - 1)
    a.branch("brnz", "default", RT=11)
    a.op("ila", RT=13, I18=TABLE_LS)
    a.op("shli", RT=12, RA=10, I7=2)
    a.op("lqx", RT=14, RA=13, RB=12)
    a.op("a", RT=15, RA=13, RB=12)
    a.op("rotqby", RT=16, RA=14, RB=15)
    a.op("bi", RA=16)
    for case, result in enumerate(TABLE_RESULTS):
        a.label("case%d" % case)
        a.op("il", RT=20, I16=result)
        a.branch("br", "done")
    a.label("default")
    a.op("il", RT=20, I16=TABLE_DEFAULT)
    a.label("done")
    a.op("ila", RT=21, I18=BUF_LS)
    a.op("stqd", RT=20, I10x16=0, RA=21)
    a.wrch(WR_OUT_MBOX, 20)
    a.stop(0x102)
    words = a.words()
    table = b"".join(a.addr("case%d" % case).to_bytes(4, "big") for case in range(TABLE_ENTRIES))
    return Program("jump_table", words, ((TABLE_LS, table),), jump_tables=1)


def throw_event() -> Program:
    """Throws an event on EVENT_PORT, waits for the PPU's reply and exits with the reply plus one."""
    a = Assembler(CODE_LS)
    a.op("il", RT=10, I16=EVENT_DATA3)
    a.wrch(WR_OUT_MBOX, 10)                 # data3 of the event
    # WrOutIntrMbox: throw_event code 64 + port in the top byte, the event value in the low 24 bits.
    a.op("ilhu", RT=11, U16=(64 + EVENT_PORT) << 8)
    a.op("iohl", RT=11, U16=EVENT_VALUE)
    a.wrch(WR_OUT_INTR_MBOX, 11)
    a.rdch(12, RD_IN_MBOX)
    a.op("ai", RT=12, RA=12, I10=1)
    a.wrch(WR_OUT_MBOX, 12)
    a.stop(0x102)
    return Program("throw_event", a.words())


PROGRAMS: tuple[Callable[[], Program], ...] = (sum_array, atomic_counter, jump_table, throw_event)


# --- images -----------------------------------------------------------------------------------


def _padded(data: bytes) -> bytes:
    # Whole 16-byte units, so that the runtime's image tracking tags every byte of a segment.
    return data + bytes(-len(data) % 16)


def build_image(program: Program, index: int) -> spu_images.SpuImage:
    ea = IMAGE_EA + index * IMAGE_STRIDE
    code = _padded(b"".join(w.to_bytes(4, "big") for w in program.words))
    blob = code
    segments = [spu_images.SpuSegment(ea, CODE_LS, len(code), len(code), True, 0)]
    for ls, data in program.data:
        data = _padded(data)
        segments.append(spu_images.SpuSegment(ea + len(blob), ls, len(data), len(data), False, len(blob)))
        blob += data
    if len(blob) > IMAGE_STRIDE:
        raise ProgramError("%s: image is larger than the stride 0x%x" % (program.name, IMAGE_STRIDE))
    doc = {"name": program.name, "container": "eboot", "ea": "0x%x" % ea, "kind": "raw", "role": "raw_thread",
           "size": "0x%x" % len(blob), "ls_base": "0x%x" % CODE_LS, "entry": "0x%x" % CODE_LS,
           "lowering": "stackfree", "gate": False, "extra_entries": []}
    entry = spu_images.parse_registry({"schema": spu_images.SCHEMA, "images": [doc]}).images[0]
    ls_end = max(s.ls + s.memsz for s in segments)
    return spu_images.SpuImage(entry, blob, hashlib.sha256(blob).hexdigest(), tuple(segments), CODE_LS, ls_end,
                               CODE_LS)


def emit_program(program: Program, index: int) -> spu_emit.ImageResult:
    image = build_image(program, index)
    rec = spu_recover.recover_image(image, image.sha256)
    result = rec.result
    name = program.name
    if not result.converged:
        raise ProgramError("%s: recovery did not converge" % name)
    if result.rejected_seeds or result.rejected_calls or result.invalid_flow:
        raise ProgramError("%s: flow runs into a word that is not code" % name)
    if result.unresolved_indirect:
        site = result.unresolved_indirect[0]
        raise ProgramError("%s: unresolved indirect branch at 0x%05x (%s)" % (name, site.site, site.reason))
    if len(rec.tables.tables) != program.jump_tables:
        raise ProgramError("%s: expected %d jump tables, recovery found %d"
                           % (name, program.jump_tables, len(rec.tables.tables)))
    db = spu_emit.parse_database(spu_recover.build_database(rec))
    spu_emit.check_database(db, image, image.sha256)
    emitted = spu_emit.emit_one(image, db)
    if emitted.unhandled:
        raise ProgramError("%s: %d unhandled words (%s)" % (
            name, emitted.unhandled, ", ".join(sorted(emitted.stats.unhandled))))
    if emitted.stats.invalid_flow or emitted.stats.unlisted_targets:
        raise ProgramError("%s: emitted flow leaves the dispatchable blocks" % name)
    return emitted


# --- files ------------------------------------------------------------------------------------


def _byte_rows(data: bytes) -> str:
    rows = []
    for at in range(0, len(data), 16):
        rows.append("    " + ", ".join("0x%02x" % b for b in data[at:at + 16]) + ",")
    return "\n".join(rows)


def render_data(programs: Sequence[Program], results: Sequence[spu_emit.ImageResult]) -> tuple[str, str]:
    """Header and source text of the image bytes and shared constants."""
    names = [p.name for p in programs]
    constants = [("kSpuProgramCount", len(programs))]
    constants += [("kSpuProg_%s" % n, i) for i, n in enumerate(names)]
    constants += [("kSpuProgCodeLs", CODE_LS), ("kSpuProgBufLs", BUF_LS), ("kSpuProgChunkBytes", CHUNK_BYTES),
                  ("kSpuProgCounterRounds", COUNTER_ROUNDS), ("kSpuProgTableEntries", TABLE_ENTRIES),
                  ("kSpuProgTableDefault", TABLE_DEFAULT), ("kSpuProgEventDataValue", EVENT_DATA3),
                  ("kSpuProgEventPort", EVENT_PORT), ("kSpuProgEventValue", EVENT_VALUE)]
    constants += [("kSpuProgTableResult%d" % i, v) for i, v in enumerate(TABLE_RESULTS)]
    header = "\n".join([
        BANNER, "#pragma once", "", "#include <stdint.h>", "", "#ifdef __cplusplus", 'extern "C" {', "#endif", "",
        "enum {", *("    %s = 0x%x," % (n, v) for n, v in constants), "};", "",
        "// The bytes of image i of kTox2SpuImages, as they sit in guest memory at the image's ea.",
        "extern const uint8_t* const kSpuProgramBytes[kSpuProgramCount];", "",
        "#ifdef __cplusplus", '}  // extern "C"', "#endif", ""])
    parts = [BANNER, "", '#include "%s"' % HEADER_NAME, ""]
    for i, result in enumerate(results):
        parts += ["static const uint8_t kBytes%d[] = {" % i, _byte_rows(result.image.data), "};", ""]
    parts += ["const uint8_t* const kSpuProgramBytes[kSpuProgramCount] = {"]
    parts += ["    kBytes%d," % i for i in range(len(results))]
    parts += ["};", ""]
    return header, "\n".join(parts)


def generate(out_dir: Path) -> bool:
    """Write the generated tree (only files that changed); True if anything changed."""
    programs = [make() for make in PROGRAMS]
    results = [emit_program(p, i) for i, p in enumerate(programs)]
    files = spu_emit.output_files(results)
    changed = spu_emit.write_output(out_dir, files, results) > 0
    header, source = render_data(programs, results)
    changed = write_if_changed(out_dir / HEADER_NAME, header) or changed
    changed = write_if_changed(out_dir / SOURCE_NAME, source) or changed
    return changed


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m tests.spu_programs.gen",
                                     description="Generate the whole-program SPU test sources.")
    parser.add_argument("--out", required=True, type=Path, help="output directory")
    args = parser.parse_args(argv)
    try:
        changed = generate(args.out)
    except ProgramError as e:
        print("error: %s" % e, file=sys.stderr)
        return 1
    except CliError as e:
        print("error: %s" % e, file=sys.stderr)
        return e.code
    print("spu programs: %d images, %s" % (len(PROGRAMS), "written" if changed else "unchanged"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
