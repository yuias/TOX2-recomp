_SOURCE_HELPERS = """\
// Mismatch reporting uses builtins only, so the file compiles without a C library.
[[maybe_unused]] static uint32_t putStr(char* msg, uint32_t size, uint32_t pos, const char* s) {
    while (*s != '\\0' && pos + 1 < size) msg[pos++] = *s++;
    return pos;
}

[[maybe_unused]] static uint32_t putHex(char* msg, uint32_t size, uint32_t pos, uint64_t v, uint32_t digits) {
    for (uint32_t i = digits; i > 0 && pos + 1 < size; i--) {
        msg[pos++] = "0123456789abcdef"[(v >> (4 * (i - 1))) & 15];
    }
    return pos;
}

// `digits` > 16 prints `hi` first (vector values); `addr` < 0 means "no index".
[[maybe_unused]] static void report(char* msg, uint32_t size, const char* field, int64_t addr, uint32_t digits,
                                    uint64_t exp_hi, uint64_t exp_lo, uint64_t got_hi, uint64_t got_lo) {
    if (size == 0) return;
    uint32_t pos = putStr(msg, size, 0, field);
    if (addr >= 0) {
        pos = putStr(msg, size, pos, "[0x");
        pos = putHex(msg, size, pos, (uint64_t)addr, 8);
        pos = putStr(msg, size, pos, "]");
    }
    pos = putStr(msg, size, pos, ": expected 0x");
    if (digits > 16) pos = putHex(msg, size, pos, exp_hi, digits - 16);
    pos = putHex(msg, size, pos, exp_lo, digits > 16 ? 16 : digits);
    pos = putStr(msg, size, pos, " got 0x");
    if (digits > 16) pos = putHex(msg, size, pos, got_hi, digits - 16);
    pos = putHex(msg, size, pos, got_lo, digits > 16 ? 16 : digits);
    msg[pos] = '\\0';
}

// The check helpers return 1 on a mismatch; `n` is the count so far, and only the first is reported.
[[maybe_unused]] static uint32_t checkU64(char* msg, uint32_t size, uint32_t n, const char* field, uint32_t digits,
                                          uint64_t got, uint64_t expected) {
    if (got == expected) return 0;
    if (n == 0) report(msg, size, field, -1, digits, 0, expected, 0, got);
    return 1;
}

// Lanes are compared through the big-endian word view, so a register prints as the ISA shows it.
[[maybe_unused]] static uint32_t checkVr(char* msg, uint32_t size, uint32_t n, const char* field, Tox2Vr got,
                                         uint32_t w0, uint32_t w1, uint32_t w2, uint32_t w3) {
    uint64_t exp_hi = (uint64_t)w0 << 32 | w1, exp_lo = (uint64_t)w2 << 32 | w3;
    uint64_t got_hi = (uint64_t)tox2VrBeWord(got, 0) << 32 | tox2VrBeWord(got, 1);
    uint64_t got_lo = (uint64_t)tox2VrBeWord(got, 2) << 32 | tox2VrBeWord(got, 3);
    if (got_hi == exp_hi && got_lo == exp_lo) return 0;
    if (n == 0) report(msg, size, field, -1, 32, exp_hi, exp_lo, got_hi, got_lo);
    return 1;
}

[[maybe_unused]] static uint32_t checkMem(char* msg, uint32_t size, uint32_t n, const uint8_t* ls, uint32_t addr,
                                          const uint8_t* expected, uint32_t count) {
    for (uint32_t i = 0; i < count; i++) {
        if (ls[addr + i] == expected[i]) continue;
        if (n == 0) report(msg, size, "ls", addr + i, 2, 0, expected[i], 0, ls[addr + i]);
        return 1;
    }
    return 0;
}

// An expected sequence of recorded events must match exactly, count included.
[[maybe_unused]] static uint32_t checkSeq(char* msg, uint32_t size, uint32_t n, const char* field,
                                          const uint64_t* got, uint32_t got_count, const uint64_t* expected,
                                          uint32_t count) {
    for (uint32_t i = 0; i < count && i < got_count; i++) {
        if (got[i] == expected[i]) continue;
        if (n == 0) report(msg, size, field, i, 16, 0, expected[i], 0, got[i]);
        return 1;
    }
    if (got_count == count) return 0;
    if (n == 0) report(msg, size, field, -1, 8, 0, count, 0, got_count);
    return 1;
}
"""


def _check_unique(prototypes: Iterable[str]) -> None:
    # A case `a` with an entry at 0x01000 and a case named `a_01000` cannot collide today, but the
    # check keeps the guarantee if the naming changes.
    seen: set[str] = set()
    for proto in prototypes:
        if proto in seen:
            raise CaseError("duplicate generated function %s" % proto[len("TOX2_SPU_FUNC("):-2])
        seen.add(proto)


def render(cases: Sequence[Case]) -> tuple[str, str]:
    """Header and source text for `cases` (raises CaseError)."""
    seen_cases: set[str] = set()
    prototypes: list[str] = []
    bodies: list[str] = []
    rows: list[str] = []
    for case in cases:
        if case.name in seen_cases:
            raise CaseError("duplicate case name %r" % case.name)
        seen_cases.add(case.name)
        protos, body, channels, entry_count = _render_case(case)
        prototypes.extend(protos)
        bodies.append(body)

        def ref(kind: str, items: list) -> tuple[str, int]:
            return ("%s_%s" % (kind, case.name) if items else "nullptr", len(items))

        reads, read_count = ref("reads", channels["reads"])
        counts, count_count = ref("counts", channels["counts"])
        leaves, leave_count = ref("leave_stops", channels["stop_leave"])
        leave_chs, leave_ch_count = ref("leave_channels", channels["leave_channels"])
        rows.append('    { .name = "%s", .init = init_%s, .check = check_%s,\n'
                    "      .entries = entries_%s, .entry_count = %d,\n"
                    "      .reads = %s, .read_count = %d, .counts = %s, .count_count = %d,\n"
                    "      .leave_stops = %s, .leave_stop_count = %d,\n"
                    "      .leave_channels = %s, .leave_channel_count = %d },"
                    % (case.name, case.name, case.name, case.name, entry_count, reads, read_count,
                       counts, count_count, leaves, leave_count, leave_chs, leave_ch_count))
    _check_unique(prototypes)

    header = "\n".join([BANNER, _HEADER_HEAD.rstrip("\n"), ""] + prototypes + [
        "",
        "extern const Tox2SemanticsCase kTox2SemanticsCases[];",
        "extern const uint32_t kTox2SemanticsCaseCount;",
        ""])
    source = "\n".join([BANNER, "", '#include "%s"' % HEADER_NAME, "", _SOURCE_HELPERS]
                       + bodies
                       + ["const Tox2SemanticsCase kTox2SemanticsCases[] = {"] + rows + ["};",
                          "const uint32_t kTox2SemanticsCaseCount = %d;" % len(rows), ""])
    return header, source


def generate(cases: Sequence[Case], out_dir: Path) -> bool:
    """Write both files (only when changed); True if either changed. Nothing is written on error."""
    header, source = render(cases)
    changed = write_if_changed(out_dir / HEADER_NAME, header)
    changed = write_if_changed(out_dir / SOURCE_NAME, source) or changed
    return changed


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m tests.spu_semantics.gen",
                                     description="Generate the SPU semantics harness C files.")
    parser.add_argument("--out", required=True, type=Path, help="output directory")
    args = parser.parse_args(argv)
    try:
        cases = load_cases()
        changed = generate(cases, args.out)
    except CaseError as e:
        print("error: %s" % e, file=sys.stderr)
        return 1
    except CliError as e:
        print("error: %s" % e, file=sys.stderr)
        return e.code
    print("spu semantics: %d cases, %s" % (len(cases), "written" if changed else "unchanged"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
