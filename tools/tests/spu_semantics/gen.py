"""C generator of the SPU semantics harness: `python -m tests.spu_semantics.gen --out DIR` (cwd tools/).

Every `CASES` entry of the `cases_<group>` modules that exist is recovered and emitted through the real
`spu_emit_core` with the stack-free lowering and written to `spu_semantics_cases.h` / `.c`. Per case the
C side gets the emitted functions, an init function, a check function, the dispatch table (with check
words, as `spu-emit` writes it) and a `kTox2SemanticsCases[]` row; the driver
(`runtime/tests/spu_semantics_main.c`) runs init, enters the case, then runs check.
"""

