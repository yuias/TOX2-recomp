HEADER_NAME = "spu_semantics_cases.h"
SOURCE_NAME = "spu_semantics_cases.c"
BANNER = "// Generated by tests.spu_semantics.gen; do not edit."
GROUPS = ("control", "int", "perm", "mem", "chan", "fp_single", "fp_double")
LOG_SIZE = 64
TERMINATOR_STOP = 0x102

_NAME_RE = re.compile(r"[a-z0-9_]+")
_REG_RE = re.compile(r"r([0-9]|[1-9][0-9]|1[01][0-9]|12[0-7])")
_MASK32 = 0xFFFFFFFF
_CHANNEL_KEYS = frozenset({"reads", "counts", "writes", "stops", "stop_leave", "halts", "leave_channels"})


class CaseError(Exception):
    """A case cannot be turned into C; the message is one line."""


def load_cases() -> list[Case]:
    """`CASES` of every `cases_<group>` module that exists, in group order."""
    package = __package__ or "tests.spu_semantics"
    cases: list[Case] = []
    for group in GROUPS:
        module_name = "%s.cases_%s" % (package, group)
        if importlib.util.find_spec(module_name) is None:
            continue
        cases.extend(importlib.import_module(module_name).CASES)
    return cases


# --- state keys -------------------------------------------------------------------------------

def _int_in(case: Case, key: str, value: object, low: int, high: int) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or not low <= value <= high:
        raise CaseError("case %s: %s=%r is not an integer in %d..%d" % (case.name, key, value, low, high))
    return value


def _normalize(case: Case, key: str, value: object) -> tuple[str, int, object]:
    """(kind, index, canonical value) of a state entry; raises CaseError on unknown keys."""
    m = _REG_RE.fullmatch(key)
    if m:
        if not isinstance(value, (tuple, list)) or len(value) != 4:
            raise CaseError("case %s: %s must be a 4-tuple of u32 words" % (case.name, key))
        return "gpr", int(m.group(1)), tuple(_int_in(case, key, w, 0, _MASK32) for w in value)
    if key == "fpscr":
        if not isinstance(value, (tuple, list)) or len(value) != 4:
            raise CaseError("case %s: fpscr must be a 4-tuple of u32 words" % case.name)
        return "fpscr", 0, tuple(_int_in(case, key, w, 0, _MASK32) for w in value)
    if key == "srr0":
        return "srr0", 0, _int_in(case, key, value, 0, _MASK32)
    if key == "int_enabled":
        return "int_enabled", 0, _int_in(case, key, value, 0, 1)
    raise CaseError("case %s: unknown state key %r" % (case.name, key))


def _state(case: Case, mapping: Mapping[str, object]) -> list[tuple[str, str, int, object]]:
    # Sorted so that the output does not depend on dict order.
    return [(key, *_normalize(case, key, mapping[key])) for key in sorted(mapping)]


def _words_expr(value: object) -> str:
    return ", ".join(u32(w) for w in value)


def _init_stmt(kind: str, index: int, value: object) -> str:
    if kind == "gpr":
        return "ctx->gpr[%d] = tox2VrFromBeWords(%s);" % (index, _words_expr(value))
    if kind == "fpscr":
        return "ctx->fpscr = tox2VrFromBeWords(%s);" % _words_expr(value)
    if kind == "srr0":
        return "ctx->srr0 = %s;" % u32(value)
    return "ctx->int_enabled = %d;" % value


def _check_stmt(key: str, kind: str, index: int, value: object) -> str:
    if kind in ("gpr", "fpscr"):
        got = "ctx->gpr[%d]" % index if kind == "gpr" else "ctx->fpscr"
        return 'n += checkVr(msg, msg_size, n, "%s", %s, %s);' % (key, got, _words_expr(value))
    if kind == "srr0":
        return 'n += checkU64(msg, msg_size, n, "srr0", 8, ctx->srr0, %s);' % u32(value)
    return 'n += checkU64(msg, msg_size, n, "int_enabled", 1, ctx->int_enabled, %du);' % value


def _blob(case: Case, what: str, addr: object, data: object) -> tuple[int, bytes]:
    if isinstance(addr, bool) or not isinstance(addr, int):
        raise CaseError("case %s: %s address %r is not an integer" % (case.name, what, addr))
    if not isinstance(data, (bytes, bytearray)) or not data:
        raise CaseError("case %s: %s at 0x%x needs non-empty bytes" % (case.name, what, addr))
    if addr < DATA_START or addr + len(data) > DATA_END:
        raise CaseError("case %s: %s range 0x%x..0x%x leaves the data window 0x%x..0x%x"
                        % (case.name, what, addr, addr + len(data), DATA_START, DATA_END))
    return addr, bytes(data)


def _byte_array(data: bytes) -> str:
    return "(const uint8_t[]){%s}" % ", ".join("0x%02x" % b for b in data)


# --- channels ---------------------------------------------------------------------------------

def _channel_number(case: Case, what: str, ch: object) -> int:
    return _int_in(case, what, ch, 0, 127)


def _channels(case: Case) -> dict[str, list]:
    """Validated channel script: reads and counts as (channel, value) lists, expectations as lists."""
    raw = case.channels
    unknown = sorted(set(raw) - _CHANNEL_KEYS)
    if unknown:
        raise CaseError("case %s: unknown channels key %r" % (case.name, unknown[0]))
    out: dict[str, list] = {"reads": [], "counts": [], "writes": None, "stops": None, "stop_leave": [],
                            "leave_channels": []}
    for ch, values in sorted(dict(raw.get("reads", {})).items()):
        _channel_number(case, "reads channel", ch)
        if not isinstance(values, (tuple, list)) or not values:
            raise CaseError("case %s: reads of channel %r need a non-empty tuple" % (case.name, ch))
        out["reads"] += [(ch, _int_in(case, "read value", v, 0, _MASK32)) for v in values]
    for ch, n in sorted(dict(raw.get("counts", {})).items()):
        _channel_number(case, "counts channel", ch)
        out["counts"].append((ch, _int_in(case, "count", n, 0, _MASK32)))
    if "writes" in raw:
        out["writes"] = [(_channel_number(case, "writes channel", ch), _int_in(case, "write value", v, 0, _MASK32))
                         for ch, v in raw["writes"]]
    if "stops" in raw:
        out["stops"] = [_int_in(case, "stop code", c, 0, 0x3FFF) for c in raw["stops"]]
    out["stop_leave"] = [_int_in(case, "stop_leave code", c, 0, 0x3FFF) for c in raw.get("stop_leave", ())]
    out["leave_channels"] = [_channel_number(case, "leave_channels channel", ch)
                             for ch in raw.get("leave_channels", ())]
    # Every case checks its halts; no key means none were taken.
    out["halts"] = [_int_in(case, "halt site", s, 0, 0x3FFFC) for s in raw.get("halts", ())]
    for what in ("writes", "stops", "halts"):
        if out[what] is not None and len(out[what]) > LOG_SIZE:
            raise CaseError("case %s: more than %d expected %s" % (case.name, LOG_SIZE, what))
    return out


# --- code -------------------------------------------------------------------------------------

def _case_words(case: Case) -> tuple[int, ...]:
    words = case.words
    if (not isinstance(words, (tuple, list)) or not words
            or not all(isinstance(w, int) and not isinstance(w, bool) and 0 < w <= _MASK32 for w in words)):
        raise CaseError("case %s: words must be a non-empty tuple of non-zero 32-bit words" % case.name)
    last = spu.decode(words[-1], CODE_BASE + 4 * (len(words) - 1))
    if last.spec is None:
        raise CaseError("case %s: the last word is not an SPU instruction" % case.name)
    out = tuple(words)
    if flow_of(last).falls_through:
        # The case ends in the thread-ending stop, as the PPU harness ends in blr.
        out += (spu_asm.encode("stop", STOP=TERMINATOR_STOP),)
    if CODE_BASE + 4 * len(out) > DATA_START:
        raise CaseError("case %s: code reaches the data window at 0x%x" % (case.name, DATA_START))
    return out


def _emit_case(case: Case, words: tuple[int, ...]) -> tuple[ImageModel, list[str]]:
    for entry in case.entries:
        if (isinstance(entry, bool) or not isinstance(entry, int) or entry % 4
                or not CODE_BASE <= entry < CODE_BASE + 4 * len(words)):
            raise CaseError("case %s: bad entry %r (need a 4-aligned address inside the code)" % (case.name, entry))
    code = SpuCode.from_words(CODE_BASE, words)
    result = recover(code, CODE_BASE, case.entries)
    if not result.converged:
        raise CaseError("case %s: recovery did not converge" % case.name)
    if result.rejected_seeds:
        raise CaseError("case %s: entry 0x%x is not code" % (case.name, result.rejected_seeds[0][0]))
    if result.invalid_flow or result.rejected_calls:
        raise CaseError("case %s: flow runs into a word that is not code" % case.name)

    owned: set[int] = set()
    for fn in result.functions.values():
        owned |= fn.addrs
    dispatchable: set[int] = set()
    for fn in result.functions.values():
        dispatchable.add(fn.entry)
        dispatchable.update(site for site in fn.return_sites() if site in owned)
    for const in result.constant_targets:
        if const.image == "self" and const.target in owned:
            dispatchable.add(const.target)

    lowering = get_lowering("stackfree")
    model = ImageModel(case.name, code, {fn.entry: fn.addrs for fn in result.functions.values()},
                       dispatchable, lambda _entry: lowering)
    stats = EmitStats()
    texts = [emit_function(model, entry, stats).text for entry in model.functions]
    if stats.unhandled:
        keys = ", ".join("%s x%d" % (key, count) for key, count in sorted(stats.unhandled.items()))
        raise CaseError("case %s: unhandled words (%s)" % (case.name, keys))
    if stats.invalid_flow:
        raise CaseError("case %s: flow runs into a word that is not code" % case.name)
    return model, texts


def _render_case(case: Case) -> tuple[list[str], str, dict[str, list], int]:
    """(prototype lines, function/init/check/table text, channel script, entry count) of one case."""
    if not isinstance(case.name, str) or not _NAME_RE.fullmatch(case.name):
        raise CaseError("invalid case name %r (need [a-z0-9_]+)" % (case.name,))
    if not isinstance(case.ref, str) or not case.ref.startswith(("SPU ISA 1.2", "CBEA 1.02")):
        raise CaseError("case %s: ref must cite 'SPU ISA 1.2' or 'CBEA 1.02'" % case.name)
    words = _case_words(case)
    model, texts = _emit_case(case, words)
    channels = _channels(case)
    name = case.name

    code_bytes = b"".join(w.to_bytes(4, "big") for w in words)
    init_lines = ["(void)ctx;", "(void)ls;",
                  "__builtin_memcpy(ls + %s, %s, %du);" % (u32(CODE_BASE), _byte_array(code_bytes), len(code_bytes))]
    for key, kind, index, value in _state(case, case.init):
        init_lines.append(_init_stmt(kind, index, value))
    for addr, data in sorted(_blob(case, "ls_init", a, d) for a, d in case.ls_init.items()):
        init_lines.append("__builtin_memcpy(ls + %s, %s, %du);" % (u32(addr), _byte_array(data), len(data)))

    check_lines = ["(void)ctx;", "(void)ls;", "(void)log;", "(void)msg;", "(void)msg_size;", "uint32_t n = 0;"]
    for key, kind, index, value in _state(case, case.expect):
        check_lines.append(_check_stmt(key, kind, index, value))
    for addr, data in sorted(_blob(case, "ls_expect", a, d) for a, d in case.ls_expect.items()):
        check_lines.append("n += checkMem(msg, msg_size, n, ls, %s, %s, %du);" % (u32(addr), _byte_array(data), len(data)))
    if channels["writes"] is not None:
        values = ", ".join("0x%08x%08xull" % (ch, v) for ch, v in channels["writes"])
        check_lines.append('n += checkSeq(msg, msg_size, n, "writes", log->writes, log->write_count, '
                           "(const uint64_t[]){%s}, %du);" % (values or "0", len(channels["writes"])))
    if channels["stops"] is not None:
        values = ", ".join("0x%xull" % c for c in channels["stops"])
        check_lines.append('n += checkSeq(msg, msg_size, n, "stops", log->stops, log->stop_count, '
                           "(const uint64_t[]){%s}, %du);" % (values or "0", len(channels["stops"])))
    values = ", ".join("0x%xull" % s for s in channels["halts"])
    check_lines.append('n += checkSeq(msg, msg_size, n, "halts", log->halts, log->halt_count, '
                       "(const uint64_t[]){%s}, %du);" % (values or "0", len(channels["halts"])))
    check_lines.append("return n;")

    def pairs(label: str, items: list[tuple[int, int]]) -> str:
        if not items:
            return ""
        rows = "".join("    { %du, %s },\n" % (ch, u32(v)) for ch, v in items)
        return "static const Tox2SemanticsPair %s_%s[] = {\n%s};\n\n" % (label, name, rows)

    tables = pairs("reads", channels["reads"]) + pairs("counts", channels["counts"])
    if channels["stop_leave"]:
        tables += "static const uint32_t leave_stops_%s[] = { %s };\n\n" % (
            name, ", ".join("0x%xu" % c for c in channels["stop_leave"]))
    if channels["leave_channels"]:
        tables += "static const uint32_t leave_channels_%s[] = { %s };\n\n" % (
            name, ", ".join("%du" % c for c in channels["leave_channels"]))

    entry_rows = []
    for addr in sorted(model.dispatchable):
        check = check_words(model, addr)
        entry_rows.append("    { %s, %du, { %s }, %s }," % (
            u32(addr), len(check), ", ".join(u32(w) for w in check), model.func_name(model.owner[addr])))

    body = ["// %s" % _comment_text("%s: %s" % (name, case.ref)), "\n".join(texts), tables.rstrip("\n"),
            "static void init_%s(Tox2SpuContext* ctx, uint8_t* ls) {" % name]
    body += ["    " + line for line in init_lines] + ["}", ""]
    body.append("static uint32_t check_%s(Tox2SpuContext* ctx, const uint8_t* ls, const Tox2SemanticsLog* log,"
                % name)
    body.append("                           char* msg, uint32_t msg_size) {")
    body += ["    " + line for line in check_lines] + ["}", ""]
    body.append("static const Tox2SpuEntry entries_%s[] = {" % name)
    body += entry_rows + ["};", ""]
    prototypes = ["TOX2_SPU_FUNC(%s);" % model.func_name(entry) for entry in model.functions]
    return prototypes, "\n".join(body), channels, len(entry_rows)


