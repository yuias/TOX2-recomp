"""C generator of the semantics harness: `python -m tests.ppu_semantics.gen --out DIR` (cwd tools/).

Every `CASES` entry of the `cases_<group>` modules that exist is emitted through
`emit_core.emit_function` and written to `ppu_semantics_cases.h` / `ppu_semantics_cases.c`.
Per case the C side gets an init function, a check function and a `kDalSemanticsCases[]` row;
the driver (`runtime/tests/ppu_semantics_main.c`) runs init, the case entry, then check.
"""

from __future__ import annotations

import argparse
import importlib
import importlib.util
import re
import struct
import sys
from collections.abc import Iterable, Mapping, Sequence
from pathlib import Path

from ps3recomp.emit_core import EmitEnv, EmitStats, _comment_text, emit_function, u32, u64
from ps3recomp.emit_db import GROUPS
from ps3recomp.emit_output import write_if_changed
from ps3recomp.info import CliError
from ps3recomp.ppu import decode
from ps3recomp.ppu_flow import CodeImage, flow_of
from tests import ppc_asm as asm

from . import CALLEE_BASE, CODE_BASE, DATA_END, DATA_START, Case

HEADER_NAME = "ppu_semantics_cases.h"
SOURCE_NAME = "ppu_semantics_cases.c"
BANNER = "// Generated by tests.ppu_semantics.gen; do not edit."

_NAME_RE = re.compile(r"[a-z0-9_]+")
_REG_RE = re.compile(r"([rfv])([0-9]|[12][0-9]|3[01])")
_CRF_RE = re.compile(r"cr([0-7])")
_MASK32 = 0xFFFFFFFF
_MASK64 = 0xFFFFFFFFFFFFFFFF
_FLAG_KEYS = ("xer_so", "xer_ov", "xer_ca", "vscr_sat", "vscr_nj")
_SCALAR_KEYS = {"lr": "lr", "ctr": "ctr", "vrsave": "vrsave", "fpscr": "fpscr"}


class CaseError(Exception):
    """A case cannot be turned into C; the message is one line."""


def load_cases() -> list[Case]:
    """`CASES` of every `cases_<group>` module that exists, in group order."""
    package = __package__ or "tests.ppu_semantics"
    cases: list[Case] = []
    for group in GROUPS:
        module_name = "%s.cases_%s" % (package, group)
        if importlib.util.find_spec(module_name) is None:
            continue
        cases.extend(importlib.import_module(module_name).CASES)
    return cases


# --- state keys -------------------------------------------------------------------------------

def _int_in(case: Case, key: str, value: object, low: int, high: int) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or not low <= value <= high:
        raise CaseError("case %s: %s=%r is not an integer in %d..%d" % (case.name, key, value, low, high))
    return value


def _normalize(case: Case, key: str, value: object) -> tuple[str, int, object]:
    """(kind, index, canonical value) of a state entry; raises CaseError on unknown keys."""
    m = _REG_RE.fullmatch(key)
    if m:
        index = int(m.group(2))
        if m.group(1) == "r":
            return "gpr", index, _int_in(case, key, value, -(1 << 63), _MASK64) & _MASK64
        if m.group(1) == "f":
            if isinstance(value, float):
                return "fpr", index, struct.unpack(">Q", struct.pack(">d", value))[0]
            return "fpr", index, _int_in(case, key, value, 0, _MASK64)
        if (not isinstance(value, (tuple, list)) or len(value) != 4):
            raise CaseError("case %s: %s must be a 4-tuple of u32 words" % (case.name, key))
        return "vr", index, tuple(_int_in(case, key, w, 0, _MASK32) for w in value)
    m = _CRF_RE.fullmatch(key)
    if m:
        return "crf", int(m.group(1)), _int_in(case, key, value, 0, 15)
    if key == "cr":
        return "cr", 0, _int_in(case, key, value, 0, _MASK32)
    if key in ("lr", "ctr"):
        return key, 0, _int_in(case, key, value, -(1 << 63), _MASK64) & _MASK64
    if key in ("vrsave", "fpscr"):
        return key, 0, _int_in(case, key, value, 0, _MASK32)
    if key in _FLAG_KEYS:
        return "flag", _FLAG_KEYS.index(key), _int_in(case, key, value, 0, 1)
    if key == "xer_count":
        return key, 0, _int_in(case, key, value, 0, 0xFF)
    raise CaseError("case %s: unknown state key %r" % (case.name, key))


def _state(case: Case, mapping: Mapping[str, object]) -> list[tuple[str, str, int, object]]:
    # Sorted so that `cr` is applied before `cr0..cr7` and the output does not depend on dict order.
    return [(key, *_normalize(case, key, mapping[key])) for key in sorted(mapping)]


def _init_stmt(key: str, kind: str, index: int, value: object) -> str:
    if kind == "gpr":
        return "ctx->gpr[%d] = %s;" % (index, u64(value))
    if kind == "fpr":
        return "ctx->fpr[%d].u64 = %s;" % (index, u64(value))
    if kind == "vr":
        return "ctx->vr[%d] = dalVrFromBeWords(%s);" % (index, ", ".join(u32(w) for w in value))
    if kind == "crf":
        return "dalSetCrField(ctx, %d, %du);" % (index, value)
    if kind == "cr":
        return "dalMtcrf(ctx, 0xffu, %s);" % u32(value)
    if kind in ("lr", "ctr"):
        return "ctx->%s = %s;" % (kind, u64(value))
    if kind in ("vrsave", "fpscr"):
        return "ctx->%s = %s;" % (kind, u32(value))
    if kind == "xer_count":
        return "ctx->xer_count = %d;" % value
    return "ctx->%s = %d;" % (_FLAG_KEYS[index], value)


def _check_stmt(key: str, kind: str, index: int, value: object) -> str:
    def u64_check(got: str) -> str:
        return 'n += checkU64(msg, msg_size, n, "%s", 16, %s, %s);' % (key, got, u64(value))

    if kind == "gpr":
        return u64_check("ctx->gpr[%d]" % index)
    if kind == "fpr":
        return u64_check("ctx->fpr[%d].u64" % index)
    if kind in ("lr", "ctr"):
        return u64_check("ctx->%s" % kind)
    if kind == "vr":
        return 'n += checkVr(msg, msg_size, n, "%s", ctx->vr[%d], %s);' % (
            key, index, ", ".join(u32(w) for w in value))
    if kind == "crf":
        got, digits = "dalGetCrField(ctx, %d)" % index, 1
    elif kind == "cr":
        got, digits = "dalMfcr(ctx)", 8
    elif kind in ("vrsave", "fpscr"):
        got, digits = "ctx->%s" % kind, 8
    elif kind == "xer_count":
        got, digits = "ctx->xer_count", 2
    else:
        got, digits = "ctx->%s" % _FLAG_KEYS[index], 1
    return 'n += checkU64(msg, msg_size, n, "%s", %d, %s, %su);' % (key, digits, got, "0x%x" % value)


def _blob(case: Case, what: str, addr: object, data: object) -> tuple[int, bytes]:
    if isinstance(addr, bool) or not isinstance(addr, int):
        raise CaseError("case %s: %s address %r is not an integer" % (case.name, what, addr))
    if not isinstance(data, (bytes, bytearray)) or not data:
        raise CaseError("case %s: %s at 0x%x needs non-empty bytes" % (case.name, what, addr))
    if addr < DATA_START or addr + len(data) > DATA_END:
        raise CaseError("case %s: %s range 0x%x..0x%x leaves the data window 0x%x..0x%x"
                        % (case.name, what, addr, addr + len(data), DATA_START, DATA_END))
    return addr, bytes(data)


def _byte_array(data: bytes) -> str:
    return "(const uint8_t[]){%s}" % ", ".join("0x%02x" % b for b in data)


# --- functions --------------------------------------------------------------------------------

def _with_return(words: Iterable[int]) -> tuple[int, ...]:
    """The words, plus a `blr` when the last one falls through (or there are none)."""
    out = tuple(words)
    if not out or flow_of(decode(out[-1], 0, strict=True)).falls_through:
        out += (asm.blr(),)
    return out


def _check_words(case: Case, what: str, words: object) -> tuple[int, ...]:
    if not isinstance(words, (tuple, list)) or not all(
            isinstance(w, int) and not isinstance(w, bool) and 0 <= w <= _MASK32 for w in words):
        raise CaseError("case %s: %s must be a tuple of 32-bit words" % (case.name, what))
    return tuple(words)


def _functions(case: Case) -> dict[int, tuple[int, ...]]:
    """Entry address -> words (with return) of the case function and its callees."""
    functions = {CODE_BASE: _with_return(_check_words(case, "words", case.words))}
    if CODE_BASE + 4 * len(functions[CODE_BASE]) > CALLEE_BASE:
        raise CaseError("case %s: code reaches the callee area at 0x%x" % (case.name, CALLEE_BASE))
    spans: list[tuple[int, int]] = []
    for addr in sorted(case.callees):
        if (isinstance(addr, bool) or not isinstance(addr, int) or addr % 4
                or not CALLEE_BASE <= addr < DATA_START):
            raise CaseError("case %s: bad callee address %r (need 4-aligned, 0x%x..0x%x)"
                            % (case.name, addr, CALLEE_BASE, DATA_START))
        words = _with_return(_check_words(case, "callee 0x%x" % addr, case.callees[addr]))
        end = addr + 4 * len(words)
        if end > DATA_START or (spans and addr < spans[-1][1]):
            raise CaseError("case %s: callee 0x%x overlaps another range or the data area"
                            % (case.name, addr))
        spans.append((addr, end))
        functions[addr] = words
    return functions


def _switch_targets(case: Case, functions: Mapping[int, tuple[int, ...]]) -> dict[int, tuple[int, ...]]:
    bcctr_sites = {entry + 4 * i for entry, words in functions.items() for i, w in enumerate(words)
                   if (spec := decode(w, 0, strict=True).spec) is not None and spec.name == "bcctr"}
    out: dict[int, tuple[int, ...]] = {}
    for site, targets in case.switch_targets.items():
        if site not in bcctr_sites:
            raise CaseError("case %s: switch site 0x%x is not a bcctr word" % (case.name, site))
        if not all(isinstance(t, int) and t % 4 == 0 and CODE_BASE <= t < DATA_START for t in targets):
            raise CaseError("case %s: bad switch target at 0x%x" % (case.name, site))
        out[site] = tuple(sorted(set(targets)))
    return out


def _render_case(case: Case) -> tuple[list[str], str, list[tuple[int, str]]]:
    """(prototype lines, function/init/check/mapping text, mappings) of one case."""
    if not _NAME_RE.fullmatch(case.name):
        raise CaseError("invalid case name %r (need [a-z0-9_]+)" % (case.name,))
    if not isinstance(case.ref, str) or not case.ref.strip():
        raise CaseError("case %s: missing ref" % case.name)
    functions = _functions(case)
    names = {entry: "case_%s" % case.name if entry == CODE_BASE
             else "case_%s_%08x" % (case.name, entry) for entry in functions}
    env = EmitEnv(names, {}, _switch_targets(case, functions))
    stats = EmitStats()
    texts = []
    for entry, words in functions.items():
        image = CodeImage.from_words(entry, words)
        texts.append(emit_function(image, entry, [entry + 4 * i for i in range(len(words))], env,
                                   stats, name=names[entry]))
    if stats.unhandled:
        keys = ", ".join("%s x%d" % (key, count) for key, count in sorted(stats.unhandled.items()))
        raise CaseError("case %s: unhandled words (%s)" % (case.name, keys))

    init_lines = ["(void)ctx;", "(void)base;"]
    for key, kind, index, value in _state(case, case.init):
        init_lines.append(_init_stmt(key, kind, index, value))
    for addr, data in sorted(_blob(case, "mem_init", a, d) for a, d in case.mem_init.items()):
        init_lines.append("__builtin_memcpy(base + %s, %s, %du);"
                          % (u32(addr), _byte_array(data), len(data)))
    check_lines = ["(void)ctx;", "(void)base;", "(void)msg;", "(void)msg_size;", "uint32_t n = 0;"]
    for key, kind, index, value in _state(case, case.expect):
        check_lines.append(_check_stmt(key, kind, index, value))
    for addr, data in sorted(_blob(case, "mem_expect", a, d) for a, d in case.mem_expect.items()):
        check_lines.append("n += checkMem(msg, msg_size, n, base, %s, %s, %du);"
                           % (u32(addr), _byte_array(data), len(data)))
    check_lines.append("return n;")

    mappings = sorted((entry, names[entry]) for entry in functions)
    body = ["// %s" % _comment_text("%s: %s" % (case.name, case.ref)),
            "\n".join(texts),
            "static void init_%s(DalPpuContext* ctx, uint8_t* base) {" % case.name]
    body += ["    " + line for line in init_lines] + ["}", ""]
    body.append("static uint32_t check_%s(DalPpuContext* ctx, const uint8_t* base, char* msg,"
                % case.name)
    body.append("                           uint32_t msg_size) {")
    body += ["    " + line for line in check_lines] + ["}", ""]
    body.append("static const DalFuncMapping mappings_%s[] = {" % case.name)
    body += ["    { %s, %s }," % (u32(guest), name) for guest, name in mappings] + ["};", ""]
    return ["DAL_PPU_FUNC(%s);" % names[e] for e in sorted(names)], "\n".join(body), mappings


# --- files ------------------------------------------------------------------------------------

_HEADER_HEAD = """\
#pragma once

#include "dal/ppu.h"

// Runs before the case function; sets the registers and memory the case starts from.
typedef void DalSemanticsInitFn(DalPpuContext* ctx, uint8_t* base);
// Returns the number of mismatching expectations; for the first one it writes
// "<field>: expected 0x<value> got 0x<value>" into msg (NUL-terminated, truncated to msg_size).
typedef uint32_t DalSemanticsCheckFn(DalPpuContext* ctx, const uint8_t* base, char* msg,
                                     uint32_t msg_size);

typedef struct DalSemanticsCase {
    const char* name;
    DalPpuFunc* entry;      // guest CODE_BASE
    DalSemanticsInitFn* init;
    DalSemanticsCheckFn* check;
    const DalFuncMapping* mappings;     // entry and callees, sorted by guest address
    uint32_t mapping_count;
} DalSemanticsCase;

// Case and callee functions are named after the case and the guest address (generated names).
"""

_SOURCE_HELPERS = """\
// Mismatch reporting uses builtins only, so the file compiles without a C library.
[[maybe_unused]] static uint32_t putStr(char* msg, uint32_t size, uint32_t pos, const char* s) {
    while (*s != '\\0' && pos + 1 < size) msg[pos++] = *s++;
    return pos;
}

[[maybe_unused]] static uint32_t putHex(char* msg, uint32_t size, uint32_t pos, uint64_t v,
                                        uint32_t digits) {
    for (uint32_t i = digits; i > 0 && pos + 1 < size; i--) {
        msg[pos++] = "0123456789abcdef"[(v >> (4 * (i - 1))) & 15];
    }
    return pos;
}

// `digits` > 16 prints `hi` first (vector values); `addr` < 0 means "no address".
[[maybe_unused]] static void report(char* msg, uint32_t size, const char* field, int64_t addr,
                                    uint32_t digits, uint64_t exp_hi, uint64_t exp_lo,
                                    uint64_t got_hi, uint64_t got_lo) {
    if (size == 0) return;
    uint32_t pos = putStr(msg, size, 0, field);
    if (addr >= 0) {
        pos = putStr(msg, size, pos, "[0x");
        pos = putHex(msg, size, pos, (uint64_t)addr, 8);
        pos = putStr(msg, size, pos, "]");
    }
    pos = putStr(msg, size, pos, ": expected 0x");
    if (digits > 16) pos = putHex(msg, size, pos, exp_hi, digits - 16);
    pos = putHex(msg, size, pos, exp_lo, digits > 16 ? 16 : digits);
    pos = putStr(msg, size, pos, " got 0x");
    if (digits > 16) pos = putHex(msg, size, pos, got_hi, digits - 16);
    pos = putHex(msg, size, pos, got_lo, digits > 16 ? 16 : digits);
    msg[pos] = '\\0';
}

// The check helpers return 1 on a mismatch; `n` is the count so far, and only the first is reported.
[[maybe_unused]] static uint32_t checkU64(char* msg, uint32_t size, uint32_t n, const char* field,
                                          uint32_t digits, uint64_t got, uint64_t expected) {
    if (got == expected) return 0;
    if (n == 0) report(msg, size, field, -1, digits, 0, expected, 0, got);
    return 1;
}

[[maybe_unused]] static uint32_t checkVr(char* msg, uint32_t size, uint32_t n, const char* field,
                                         DalVr got, uint32_t w0, uint32_t w1, uint32_t w2,
                                         uint32_t w3) {
    uint64_t exp_hi = (uint64_t)w0 << 32 | w1, exp_lo = (uint64_t)w2 << 32 | w3;
    uint64_t got_hi = (uint64_t)dalVrBeWord(got, 0) << 32 | dalVrBeWord(got, 1);
    uint64_t got_lo = (uint64_t)dalVrBeWord(got, 2) << 32 | dalVrBeWord(got, 3);
    if (got_hi == exp_hi && got_lo == exp_lo) return 0;
    if (n == 0) report(msg, size, field, -1, 32, exp_hi, exp_lo, got_hi, got_lo);
    return 1;
}

[[maybe_unused]] static uint32_t checkMem(char* msg, uint32_t size, uint32_t n, const uint8_t* base,
                                          uint32_t addr, const uint8_t* expected, uint32_t count) {
    for (uint32_t i = 0; i < count; i++) {
        if (base[addr + i] == expected[i]) continue;
        if (n == 0) report(msg, size, "mem", addr + i, 2, 0, expected[i], 0, base[addr + i]);
        return 1;
    }
    return 0;
}
"""


def _check_unique(prototypes: Iterable[str]) -> None:
    # `case_a_00018000` (callee of a) could collide with a case named `a_00018000`.
    seen: set[str] = set()
    for proto in prototypes:
        if proto in seen:
            raise CaseError("duplicate generated function %s" % proto[len("DAL_PPU_FUNC("):-2])
        seen.add(proto)


def render(cases: Sequence[Case]) -> tuple[str, str]:
    """Header and source text for `cases` (raises CaseError)."""
    seen_cases: set[str] = set()
    prototypes: list[str] = []
    bodies: list[str] = []
    rows: list[str] = []
    for case in cases:
        if case.name in seen_cases:
            raise CaseError("duplicate case name %r" % case.name)
        seen_cases.add(case.name)
        protos, body, mappings = _render_case(case)
        prototypes.extend(protos)
        bodies.append(body)
        rows.append('    { .name = "%s", .entry = case_%s, .init = init_%s, .check = check_%s,\n'
                    "      .mappings = mappings_%s, .mapping_count = %d },"
                    % (case.name, case.name, case.name, case.name, case.name, len(mappings)))
    _check_unique(prototypes)

    header = "\n".join([BANNER, _HEADER_HEAD.rstrip("\n"), ""] + prototypes + [
        "",
        "extern const DalSemanticsCase kDalSemanticsCases[];",
        "extern const uint32_t kDalSemanticsCaseCount;",
        ""])
    source = "\n".join([BANNER, "", '#include "%s"' % HEADER_NAME, "", _SOURCE_HELPERS]
                       + bodies
                       + ["const DalSemanticsCase kDalSemanticsCases[] = {"] + rows + ["};",
                          "const uint32_t kDalSemanticsCaseCount = %d;" % len(rows), ""])
    return header, source


def generate(cases: Sequence[Case], out_dir: Path) -> bool:
    """Write both files (only when changed); True if either changed. Nothing is written on error."""
    header, source = render(cases)
    changed = write_if_changed(out_dir / HEADER_NAME, header)
    changed = write_if_changed(out_dir / SOURCE_NAME, source) or changed
    return changed


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m tests.ppu_semantics.gen",
                                     description="Generate the PPU semantics harness C files.")
    parser.add_argument("--out", required=True, type=Path, help="output directory")
    args = parser.parse_args(argv)
    try:
        cases = load_cases()
        changed = generate(cases, args.out)
    except CaseError as e:
        print("error: %s" % e, file=sys.stderr)
        return 1
    except CliError as e:
        print("error: %s" % e, file=sys.stderr)
        return e.code
    print("ppu semantics: %d cases, %s" % (len(cases), "written" if changed else "unchanged"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
