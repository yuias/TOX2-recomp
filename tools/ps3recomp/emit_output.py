"""Output side of the `emit` command: chunk files, import trampolines, tables, report."""

from __future__ import annotations

import struct
from collections import Counter
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path

from . import ppu
from .elf import ElfError, ElfFile
from .emit_core import EmitStats, Op, _comment_text, u32
from .emit_db import GROUP_OF, GROUPS, DbThunk
from .info import EXIT_IO, CliError

REPORT_SCHEMA = 1
THUNK_WORDS = 8
LARGEST_FUNCTIONS = 10
UNHANDLED_TOP = 10
EXAMPLE_SITES = 5

EDGE_KEYS = ("calls_direct", "calls_import", "calls_dynamic_const", "calls_indirect",
             "tails_direct", "tails_import", "tails_dynamic", "fallthrough_tails", "returns",
             "switches", "switch_cases", "syscalls", "traps")

HEADER_NAME = "ppu_funcs.h"
IMPORTS_NAME = "ppu_imports.c"
TABLES_NAME = "ppu_tables.c"
SOURCES_NAME = "sources.cmake"


def hexs(value: int) -> str:
    return "0x%08x" % value


def func_name(entry: int) -> str:
    return "fn_%08x" % entry


def import_name(addr: int) -> str:
    return "imp_%08x" % addr


def chunk_name(index: int) -> str:
    return "ppu_chunk_%03d.c" % index


def banner(sha256: str, prefix: str = "//") -> str:
    return "%s Generated by ps3tool emit from executable %s; do not edit.\n" % (prefix, sha256)


def plan_chunks(counts: Sequence[int], chunks: int) -> list[tuple[int, int]]:
    """Split functions into contiguous [start, end) groups balanced by instruction count.

    Chunk k ends at the first function where the running total reaches (k + 1) * total / chunks.
    Never returns an empty chunk, and never more than `chunks` of them.
    """
    total = sum(counts)
    result: list[tuple[int, int]] = []
    start = running = 0
    for i, count in enumerate(counts):
        running += count
        k = len(result)
        if k < chunks - 1 and running * chunks >= (k + 1) * total:
            result.append((start, i + 1))
            start = i + 1
    if start < len(counts):
        result.append((start, len(counts)))
    return result


def toc_save_statement(words: Sequence[int], addr: int) -> str | None:
    """`tox2Write64` statement for the `std r2,D(r1)` of an import stub, or None if it has none."""
    for i, word in enumerate(words):
        insn = ppu.decode(word, addr + 4 * i, strict=True)
        if insn.spec is not None and insn.spec.name == "std" and insn.field("rS") == 2 \
                and insn.field("rA") == 1:
            return "tox2Write64(base, %s, ctx->gpr[2]);" % Op(insn).ea_d("DS")
    return None


def read_thunk_words(elf: ElfFile, addr: int) -> list[int] | None:
    try:
        return list(struct.unpack(">%dI" % THUNK_WORDS, elf.read_va(addr, 4 * THUNK_WORDS)))
    except ElfError:
        return None


def render_trampoline(thunk: DbThunk, index: int,
                      words: Sequence[int] | None) -> tuple[str, bool]:
    """C text of one import trampoline and whether it saves the caller's TOC."""
    save = toc_save_statement(words, thunk.addr) if words is not None else None
    lines = ["// %s %s %s" % (_comment_text(thunk.module),
                             _comment_text(thunk.name) if thunk.name else "-",
                             hexs(thunk.fnid)),
             "TOX2_PPU_FUNC(%s) {" % import_name(thunk.addr),
             "    TOX2_ENTER(%s);" % u32(thunk.addr)]
    if save is not None:
        lines.append("    " + save)
    lines.append("    TOX2_HLE(%d);" % index)
    lines.append("}")
    return "\n".join(lines) + "\n", save is not None


def c_string(text: str | None) -> str:
    if text is None:
        return "nullptr"
    out = []
    for byte in text.encode("utf-8"):
        if 0x20 <= byte < 0x7F and chr(byte) not in '"\\?':
            out.append(chr(byte))
        else:
            out.append("\\%03o" % byte)     # fixed-width octal cannot swallow a following digit
    return '"%s"' % "".join(out)


def render_funcs_header(sha256: str, entries: Sequence[int], thunks: Sequence[DbThunk]) -> str:
    lines = [banner(sha256).rstrip("\n"), "#pragma once", "", '#include "tox2/ppu.h"', ""]
    lines += ["TOX2_PPU_FUNC(%s);" % func_name(entry) for entry in entries]
    lines += ["TOX2_PPU_FUNC(%s);" % import_name(t.addr) for t in thunks]
    return "\n".join(lines) + "\n"


def render_source(sha256: str, texts: Sequence[str]) -> str:
    """A chunk or the import file: banner, include, then the function texts."""
    head = banner(sha256) + '\n#include "%s"\n\n' % HEADER_NAME
    return head + "\n".join(texts)


def render_tables(sha256: str, entries: Sequence[int], thunks: Sequence[DbThunk]) -> str:
    mappings = sorted([(e, func_name(e)) for e in entries]
                      + [(t.addr, import_name(t.addr)) for t in thunks])
    lines = [banner(sha256).rstrip("\n"), "", '#include "%s"' % HEADER_NAME, "",
             "const Tox2FuncMapping kTox2PpuFuncMappings[] = {"]
    lines += ["    { %s, %s }," % (u32(guest), name) for guest, name in mappings]
    lines += ["};",
              "const uint32_t kTox2PpuFuncMappingCount = %d;" % len(mappings), "",
              "const Tox2ImportInfo kTox2PpuImports[] = {"]
    lines += ["    { %s, %s, %s, %s }," % (u32(t.addr), u32(t.fnid), c_string(t.module),
                                           c_string(t.name)) for t in thunks]
    lines += ["};",
              "const uint32_t kTox2PpuImportCount = %d;" % len(thunks), "",
              'const char kTox2PpuExecutableSha256[] = "%s";' % sha256]
    return "\n".join(lines) + "\n"


def render_sources(sha256: str, files: Sequence[str]) -> str:
    # CMake comments start with '#', so this file cannot use the C-style banner.
    lines = [banner(sha256, "#").rstrip("\n"), "set(TOX2_PPU_GENERATED_SOURCES"]
    lines += ['    "${CMAKE_CURRENT_LIST_DIR}/%s"' % name for name in files]
    lines.append(")")
    return "\n".join(lines) + "\n"


def write_if_changed(path: Path, text: str) -> bool:
    """Write `text` unless the file already holds it, so unchanged files keep their mtime."""
    data = text.encode("utf-8")
    try:
        if path.is_file() and path.read_bytes() == data:
            return False
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    except OSError as e:
        raise CliError(EXIT_IO, "cannot write %s: %s" % (path, e.strerror))
    return True


def remove_stale_chunks(out_dir: Path, wanted: Sequence[str]) -> None:
    keep = set(wanted)
    try:
        for path in sorted(out_dir.glob("ppu_chunk_*.c")):
            if path.name not in keep:
                path.unlink()
    except OSError as e:
        raise CliError(EXIT_IO, "cannot remove stale chunk in %s: %s" % (out_dir, e.strerror))


@dataclass
class FunctionRecord:
    entry: int
    instructions: int
    text: str


@dataclass
class OutputSummary:
    chunks: list[dict]
    output_bytes: int


def write_output(out_dir: Path, sha256: str, functions: Sequence[FunctionRecord],
                 thunks: Sequence[DbThunk], thunk_texts: Sequence[str],
                 chunk_count: int) -> OutputSummary:
    """Write the generated tree; returns the per-chunk figures for the report."""
    entries = [fn.entry for fn in functions]
    plan = plan_chunks([fn.instructions for fn in functions], chunk_count)
    files: dict[str, str] = {HEADER_NAME: render_funcs_header(sha256, entries, thunks)}
    chunk_info = []
    chunk_files = []
    for index, (start, end) in enumerate(plan):
        name = chunk_name(index)
        text = render_source(sha256, [fn.text for fn in functions[start:end]])
        files[name] = text
        chunk_files.append(name)
        chunk_info.append({"file": name, "functions": end - start,
                           "instructions": sum(fn.instructions for fn in functions[start:end]),
                           "bytes": len(text.encode("utf-8"))})
    files[IMPORTS_NAME] = render_source(sha256, thunk_texts)
    files[TABLES_NAME] = render_tables(sha256, entries, thunks)
    files[SOURCES_NAME] = render_sources(sha256, chunk_files + [IMPORTS_NAME, TABLES_NAME])

    remove_stale_chunks(out_dir, chunk_files)
    total = 0
    for name, text in files.items():
        write_if_changed(out_dir / name, text)
        total += len(text.encode("utf-8"))
    return OutputSummary(chunk_info, total)


def _sorted_counts(counts: Mapping[str, int]) -> dict[str, int]:
    return dict(sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])))


def unhandled_section(stats: EmitStats) -> dict:
    by_mnemonic = _sorted_counts(stats.unhandled)
    by_group = {group: 0 for group in GROUPS}
    invalid = 0
    for key, count in stats.unhandled.items():
        group = GROUP_OF.get(key.split(":")[0])
        if group is None:
            invalid += count
        else:
            by_group[group] += count
    if invalid:
        by_group["invalid"] = invalid       # words that do not decode; they belong to no group
    return {"total": sum(stats.unhandled.values()),
            "by_mnemonic": by_mnemonic,
            "by_group": by_group,
            "examples": {key: [hexs(a) for a in stats.unhandled_sites[key][:EXAMPLE_SITES]]
                         for key in sorted(by_mnemonic)}}


def edges_section(edges: Counter) -> dict:
    return {key: edges.get(key, 0) for key in EDGE_KEYS}


def build_report(*, sha256: str, db_sha256: str, stats: EmitStats,
                 functions: Sequence[FunctionRecord], thunks: Sequence[DbThunk],
                 without_toc_save: Sequence[int], summary: OutputSummary,
                 elapsed: float) -> dict:
    largest = sorted(functions, key=lambda fn: (-fn.instructions, fn.entry))[:LARGEST_FUNCTIONS]
    return {
        "schema": REPORT_SCHEMA,
        "generator": "ps3tool emit",
        "input": {"executable_sha256": sha256, "functions_db_sha256": db_sha256},
        "functions": stats.functions,
        "instructions": stats.instructions,
        "import_trampolines": len(thunks),
        "thunks_without_toc_save": [hexs(a) for a in without_toc_save],
        "chunks": summary.chunks,
        "largest_functions": [{"entry": hexs(fn.entry), "instructions": fn.instructions}
                              for fn in largest],
        "unhandled": unhandled_section(stats),
        "edges": edges_section(stats.edges),
        "dynamic_targets": [{"site": hexs(site), "target": hexs(target), "kind": kind}
                            for site, target, kind in stats.dynamic_targets],
        "labels": stats.labels,
        "loop_hooks": stats.loop_hooks,
        "output_bytes": summary.output_bytes,
        "elapsed_s": round(elapsed, 3),
    }


def report_lines(report: dict, out_dir: str) -> list[str]:
    unhandled = report["unhandled"]
    edges = report["edges"]
    top = ", ".join("%s %d" % kv for kv in list(unhandled["by_mnemonic"].items())[:UNHANDLED_TOP])
    return [
        "emit: %d functions (%d insns) in %d chunks, %d import trampolines (%d without TOC save)"
        % (report["functions"], report["instructions"], len(report["chunks"]),
           report["import_trampolines"], len(report["thunks_without_toc_save"])),
        "unhandled: %d words in %d mnemonics (top: %s)"
        % (unhandled["total"], len(unhandled["by_mnemonic"]), top or "none"),
        "calls: direct %d, import %d, indirect %d, dynamic %d; tails: direct %d, import %d, "
        "dynamic %d, fallthrough %d; switches %d (%d cases)"
        % (edges["calls_direct"], edges["calls_import"], edges["calls_indirect"],
           edges["calls_dynamic_const"], edges["tails_direct"], edges["tails_import"],
           edges["tails_dynamic"], edges["fallthrough_tails"], edges["switches"],
           edges["switch_cases"]),
        "output: %d bytes in %s" % (report["output_bytes"], out_dir),
        "elapsed: %.1f s" % report["elapsed_s"],
    ]
